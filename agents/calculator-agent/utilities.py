# Add: Takes two numbers and returns the sum.
def add(x, y):
    return x + y

# Subtract: Takes two numbers and returns the difference.
def subtract(x, y):
    return x - y

# Multiply: Takes two numbers and returns the product.
def multiply(x, y):
    return x * y

# Divide: Takes two numbers and returns the quotient.
def divide(x, y):
    return x / y
